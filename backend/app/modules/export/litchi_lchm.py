"""Litchi LCHM binary mission exporter.

The LCHM binary layout implemented here was reverse-engineered from real
files generated by the Litchi app (see ``backend/tests/fixtures/litchi``).
This module serializes the 44-byte header, the 56-byte waypoint records, and
(optionally) the photo-capture trailer.

Fields that are present in real files but whose meaning has not been
confirmed (header padding bytes, record offset +4 and offset +36, the second
f32 of each trailer photo block) are written as documented structural
constants (``0``) and are labelled ``UNKNOWN``. The trailer layout
(altitude-mirror blocks, capture settings, per-waypoint photo distance,
trailing bytes) is confirmed against the fixtures and M1-M6/V1/V2 and is
documented in ``docs/export/litchi-lchm-trailer-analysis.md``. The trailer is
only emitted when ``options.photo_capture`` is provided (Litchi Export
Adapter).

All fields are big-endian (verified against the fixtures).
"""

